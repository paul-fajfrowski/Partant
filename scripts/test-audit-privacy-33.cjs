const fs = require('node:fs'), ts = require('../apps/mobile/node_modules/typescript');
const assert = require('node:assert/strict');
require.extensions['.ts'] = (m,f) => m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,esModuleInterop:true}}).outputText,f);
const D = require('../apps/mobile/src/product/connectedDomain.ts');
const M = require('../apps/mobile/src/product/model.ts');
const W = require('../apps/mobile/src/product/workflows.ts');
let checks=0;const ok=(v,m)=>{assert.ok(v,m);checks++};
const coach={id:'00000000-0000-4000-8000-000000000011',email:'coach@example.invalid'};
const client={id:'00000000-0000-4000-8000-000000000012',email:'client@example.invalid'};
const other={id:'00000000-0000-4000-8000-000000000013',email:'other@example.invalid'};
let s=D.register(D.register(D.register(D.emptyConnected(),coach,'Coach','coach'),client,'Client','client'),other,'Other','client');
const secret='PRIVATE_ACCESS_33';
s.settings[coach.id]={...M.configFor(s,coach.id),published:true,dossier:{status:'approved',expires:'2099-12-31',documents:[],history:[],reason:''},preparation:{provided:secret,bring:'',meeting:secret,weather:''},locations:{Studio:{type:'Studio',name:'Studio public',address:'Adresse publique',instructions:secret}},futurePrivateSetting:secret};
const offer={id:'o33',coach:coach.id,name:'Renforcement',kind:'Groupe',duration:60,price:25,active:true,capacity:4};
s.groups=[{id:'g33',offer,day:M.addDays(M.today(),2),time:'18:00',address:'Adresse publique',preparation:{meeting:secret},locationInstructions:secret}];
s.offers=[offer];
s.bookings=[{id:'b33',coach:coach.id,clientId:client.id,clientName:'Client',day:M.addDays(M.today(),2),time:'18:00',duration:60,offerId:'o33',serviceName:'Renforcement',kind:'Groupe',format:'Studio',seats:1,price:25,goal:'',address:'Adresse publique',status:'confirmed',slotId:'g33',preparation:{meeting:secret},locationInstructions:secret}];
for(const actor of [undefined,other]){
 const p=D.project(s,actor);
 ok(p.groups.length===1,'Public group remains discoverable');
 ok(!JSON.stringify(p).includes(secret),'No private coach instruction/unknown setting in stranger response');
 ok(p.settings[coach.id].locations.Studio.address==='Adresse publique','Public location retained');
}
const own=D.project(s,coach), booked=D.project(s,client);
ok(own.settings[coach.id].preparation.meeting===secret,'Owner can edit preparation');
ok(own.groups[0].locationInstructions===secret,'Owner can edit group instructions');
ok(booked.bookings[0].locationInstructions===secret,'Participant receives booking instructions');
ok(!JSON.stringify(booked.settings).includes(secret),'No live private config shared with booked client');
ok(!JSON.stringify(booked.groups).includes(secret),'Group discovery does not expose shared private instructions');
ok(D.project(s,{...other,staff:true}).settings[coach.id].preparation.meeting===secret,'Authorized team retains support view');
s.bookings[0].status='completed';
s.calendarBusy={[coach.id]:[{day:M.addDays(M.today(),2),time:'12:00',duration:60}]};
s.calendarStatus={[coach.id]:{connected:true,updatedAt:Date.now()}};
s.coachDrafts={[coach.id+':profile']:{cfg:{studioAddress:secret}}};
s.extraCoaches[0].area=secret;
s.notices=[{id:'n33',recipient:client.id,booking:'b33',body:secret,read:false}];
const deleted=D.applyCommand(s,coach,{name:'deleteAccount',args:[]});
ok(!JSON.stringify(deleted).includes(secret),'All known locations, instructions, draft, profile, notice and booking copies erased');
ok(!deleted.settings[coach.id],'No coach settings retained');
ok(!deleted.calendarStatus[coach.id]&&!deleted.calendarBusy[coach.id],'Calendar snapshots erased');
ok(!deleted.groups.length&&!deleted.offers.length,'Deleted coach cannot publish or reopen a group');
ok(deleted.bookings[0].id==='b33'&&deleted.bookings[0].price===25,'Useful historical booking reference retained');
ok(D.project(deleted,client).bookings.length===1,'Other participant retains own history');
ok(!D.project(deleted).extraCoaches.length,'Deleted profile not in discovery');
ok(JSON.stringify(W.maintain(W.maintain(deleted)))===JSON.stringify(W.maintain(deleted)),'Erasure maintenance is idempotent');
console.log(`PASS ${checks} public projection, booking access and erasure regression checks.`);
