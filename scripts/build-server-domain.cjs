const fs = require("node:fs"),
  path = require("node:path"),
  ts = require("../apps/mobile/node_modules/typescript");
// Bundle the exact RN domain as dependency-free ESM for the Edge runtime.
const root = path.resolve(__dirname, "../apps/mobile/src/product"),
  modules = {};
function add(file) {
  const id = path.relative(root, file);
  if (modules[id]) return id;
  modules[id] = "";
  if (file.endsWith(".json")) {
    modules[id] = "module.exports=" + fs.readFileSync(file, "utf8") + ";";
    return id;
  }
  let code = ts.transpileModule(fs.readFileSync(file, "utf8"), {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
      esModuleInterop: true,
    },
  }).outputText;
  code = code.replace(/require\("(\.[^\"]+)"\)/g, (_, name) => {
    let target = path.resolve(path.dirname(file), name);
    if (!fs.existsSync(target)) target += ".ts";
    return `load(${JSON.stringify(add(target))})`;
  });
  modules[id] = code;
  return id;
}
add(path.join(root, "connectedDomain.ts"));
add(path.join(root, "workflows.ts"));
const bundle = `// Generated by scripts/build-server-domain.cjs; edit the shared TypeScript domain.\nconst modules={\n${Object.entries(
  modules,
)
  .map(
    ([id, code]) =>
      `${JSON.stringify(id)}:(module,exports,load)=>{\n${code}\n}`,
  )
  .join(
    ",\n",
  )}\n};\nconst cache={};function load(id){if(cache[id])return cache[id].exports;const m={exports:{}};cache[id]=m;modules[id](m,m.exports,load);return m.exports;}\nconst d=load('connectedDomain.ts');\nexport const {emptyConnected,register,applyCommand,project,documents}=d;\nexport const {maintain}=load('workflows.ts');\nexport const {instant}=load('model.ts');\n`;
fs.writeFileSync(
  path.resolve(__dirname, "../supabase/functions/product-api/domain.js"),
  bundle,
);
console.log("Shared domain bundled for Supabase.");

